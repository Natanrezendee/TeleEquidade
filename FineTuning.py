import json

def avaliar_modelo_gold(model, tokenizer, casos_teste):
    FastLanguageModel.for_inference(model)
    acertos = 0

    print("\n--- INICIANDO BUSTER DE VALIDAÇÃO (EXP-002) ---\n")

    for i, item in enumerate(casos_teste):
        mensagens = [
            {"role": "system", "content": "Você é um médico auditor do SISREG. Analise o caso e responda estritamente em JSON com as chaves 'prioridade' e 'motivo'."},
            {"role": "user", "content": item["caso"]}
        ]
        inputs = tokenizer.apply_chat_template(mensagens, tokenize=True, add_generation_prompt=True, return_tensors="pt").to("cuda")
        outputs = model.generate(input_ids=inputs, max_new_tokens=128, use_cache=True, temperature=0.1)
        resposta_raw = tokenizer.decode(outputs[0][inputs.shape[1]:], skip_special_tokens=True)

        # Tenta interpretar o JSON
        try:
            res_json = json.loads(resposta_raw)
            prioridade_obitda = res_json.get("prioridade", "").upper()
            status = "OK" if prioridade_obitda == item["esperado"] else "ERRO"
            if status == "OK": acertos += 1
        except:
            prioridade_obitda = "JSON_INVALIDO"
            status = "ERRO"

        print(f"Caso {i+1}: Esperado [{item['esperado']}] | Obtido [{prioridade_obitda}] -> Status: {status}")

    acuracia = (acertos / len(casos_teste)) * 100
    print(f"\nAcurácia Geral do Teste Cego: {acuracia:.2f}% ({acertos}/{len(casos_teste)})")
    return acuracia

