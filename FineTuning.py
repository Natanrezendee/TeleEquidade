# 2. Formatação com Template Nativo do Llama (Sincronizado com a Inferência)
def formatar_para_llama_native(exemplos):
    textos = []
    for c, r in zip(exemplos["caso"], exemplos["resposta"]):
        mensagens = [
            {"role": "system", "content": "Você é um médico auditor do SISREG. Analise o caso e responda estritamente em JSON com as chaves 'prioridade' e 'motivo'."},
            {"role": "user", "content": c},
            {"role": "assistant", "content": r}
        ]
        texto_formatado = tokenizer.apply_chat_template(mensagens, tokenize=False, add_generation_prompt=False)
        textos.append(texto_formatado)
    return {"text": textos}

